import assert from 'node:assert/strict';
import {monthContributions} from '../insights.js';
import {paymentInstallments, installmentKey, memberPaymentBalance, renderPaymentTable} from '../payment-ledger.js';
const members=[{id:'a',name:'A'},{id:'b',name:'B'}];
const result=monthContributions(members,[],'2026-10',new Date(2026,9,12));
const row=result.rows[0], records=new Map(), legacyRecords=new Map();
let balance=memberPaymentBalance(row,'2026-10',records);
assert.equal(balance.due,17.5);assert.equal(balance.remaining,17.5);
assert.equal(balance.items[0].amount,10);assert.equal(balance.items[1].amount,2.5);assert.equal(balance.items[2].amount,5);
assert.equal(balance.items[3].closed,false);assert.equal(balance.items[3].amount,0);
records.set(installmentKey('a','2026-10','base'),{paid:true,amount:10});
balance=memberPaymentBalance(row,'2026-10',records);assert.equal(balance.remaining,7.5);
records.set(installmentKey('a','2026-10',row.statuses[0].start),{paid:true,amount:2.5});
assert.equal(memberPaymentBalance(row,'2026-10',records).remaining,5);
assert.equal(memberPaymentBalance(result.rows[1],'2026-10',records).remaining,17.5);
assert.equal(memberPaymentBalance(row,'2026-11',records).remaining,17.5);
const legacy={paid:true,updatedAt:{toDate:()=>new Date(2026,9,5)}};
balance=memberPaymentBalance(row,'2026-10',new Map(),legacy);
assert.equal(balance.paid,12.5,'Legacy marking covers base and weeks closed when marked');assert.equal(balance.remaining,5);
records.set(installmentKey('a','2026-10','base'),{paid:false,amount:10});
assert.equal(memberPaymentBalance(row,'2026-10',records,legacy).items[0].paid,false,'Explicit unchecked overrides old marking');
assert.equal(memberPaymentBalance(row,'2026-10',new Map(),{paid:true}).paid,10,'Undated old records cannot cover later fines');
const partialRecords=new Map([[installmentKey('a','2026-10',row.statuses[1].start),{paid:true,amount:2.5}]]);
assert.equal(memberPaymentBalance(row,'2026-10',partialRecords).items[2].remaining,2.5,'Increased fine needs balance paid');
partialRecords.set(installmentKey('a','2026-10',row.statuses[1].start),{paid:true,amount:5});
const lower={...row,statuses:row.statuses.map((week,index)=>index===1?{...week,missingRuns:1}:week)};
assert.equal(memberPaymentBalance(lower,'2026-10',partialRecords).items[2].paidAmount,2.5,'Credit capped to current fine');
const options={records,legacyRecords,pending:new Map(),ready:true,isAdmin:true};
let html=renderPaymentTable(result.rows,result.weeks,'2026-10',options);
assert.equal((html.match(/class="installment-checkbox"/g)||[]).length,6,'Only base and closed nonzero fines have controls');
assert(html.includes('Neukon&#269;en&#253;'));
assert(!renderPaymentTable(result.rows,result.weeks,'2026-10',{...options,isAdmin:false}).includes('type="checkbox"'));
assert(!renderPaymentTable(result.rows,result.weeks,'2026-10',{...options,ready:false}).includes('type="checkbox"'));
const fulfilled=monthContributions([members[0]],[{memberId:'a',date:'2026-10-02',distance:3}],'2026-10',new Date(2026,9,5));
html=renderPaymentTable(fulfilled.rows,fulfilled.weeks,'2026-10',options);assert(html.includes('Bez pokuty'));
assert.equal((html.match(/class="installment-checkbox"/g)||[]).length,1);
console.log('PASS: installment dates, per-member/month isolation, legacy coverage, overrides, changed fines, zero/future weeks, admin-only controls and balances.');

const baseOnly = monthContributions([members[0]], [], '2026-11', new Date(2026,10,4));
const basePaid = new Map([[installmentKey('a','2026-11','base'),{paid:true,amount:10}]]);
const settledHtml = renderPaymentTable(baseOnly.rows,baseOnly.weeks,'2026-11',{...options,records:basePaid});
assert(settledHtml.includes('installment-balance balance-settled'));
assert(settledHtml.includes('&#10003; Zaplaten&#233;'));
assert(!renderPaymentTable(baseOnly.rows,baseOnly.weeks,'2026-11',{...options,records:new Map()}).includes('balance-settled'));
assert(!renderPaymentTable(baseOnly.rows,baseOnly.weeks,'2026-11',{...options,records:basePaid,ready:false}).includes('balance-settled'));
console.log('PASS: fully paid balances are highlighted; unpaid and unavailable balances are not.');
