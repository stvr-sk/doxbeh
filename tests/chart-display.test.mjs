import assert from 'node:assert/strict';
import {comparisonRows} from '../chart-display.js';
import {personalInsights,monthContributions} from '../insights.js';
const members=[{id:'a',nick:'first',name:'A'},{id:'b',nick:'second',name:'B'},{id:'c',nick:'zero',name:'C'}];
const runs=[{memberId:'a',date:'2026-11-12',distance:10},{memberId:'b',date:'2026-11-12',distance:20}];
const {rows}=monthContributions(members,runs,'2026-11',new Date(2026,10,13));
const original=JSON.stringify(rows);
const normal=comparisonRows(rows,'other');const target=comparisonRows(rows,'sab.dia');
assert.deepEqual(normal.map(row=>row.distance),[20,10,0]);
assert.deepEqual(target,normal,'All viewers see real credited distances');
assert.equal(target.find(row=>row.member.id==='c').distance,0);
assert.deepEqual(comparisonRows(rows,' SAB.DIA '),target);
assert.deepEqual(comparisonRows(rows,undefined),normal);
assert.deepEqual(comparisonRows(rows,'sab.diaa'),normal);
assert.deepEqual(comparisonRows(rows,'sab.dia'),target,'Stable between renders');
assert.equal(JSON.stringify(rows),original,'Underlying rows and runs are untouched');
assert.equal(personalInsights(runs,'a','2026-11',new Date(2026,10,13)).total,10);
assert.equal(rows[0].runs[0].distance,10);
console.log('PASS: all viewers see identical real credited distances; sorting, zero-distance handling and source data preserved.');
