import assert from 'node:assert/strict';
import {monthContributions} from '../insights.js';
import {weeklyGroups, selectedWeek, renderWeeklyOverview} from '../weekly-overview.js';
const members=[{id:'done',name:'Done'},{id:'partial',name:'Partial'},{id:'short',name:'Short <script>'},{id:'empty',name:'Empty'}];
const runs=[{memberId:'done',date:'2026-11-01',distance:3},{memberId:'done',date:'2026-11-03',distance:5},{memberId:'partial',date:'2026-11-02',distance:4},{memberId:'short',date:'2026-11-02',distance:2},{memberId:'short',date:'2026-11-07',distance:8}];
const {rows,weeks}=monthContributions(members,runs,'2026-11',new Date(2026,10,4));
assert.equal(selectedWeek(weeks,undefined,'2026-11-04').start,'2026-11-02');
assert.equal(selectedWeek(weeks,undefined,'2026-11-01').start,'2026-11-02','Bonus Sunday selects first week');
assert.equal(selectedWeek(weeks,weeks[1].start,'2026-11-04').start,weeks[1].start);
assert.equal(selectedWeek(weeks,'stale','2026-12-10').start,weeks.at(-1).start);
assert.equal(selectedWeek(weeks,undefined,'2026-10-01').start,weeks[0].start);
const groups=weeklyGroups(rows,weeks[0],'2026-11-04');
assert.deepEqual(groups.eligible.map(row=>row.member.id),['done']);
assert.deepEqual(groups.partial.map(row=>row.member.id),['partial']);
assert.equal(groups.empty.length,2);assert.equal(groups.empty.find(row=>row.member.id==='short').shortRuns,1);
assert.equal(groups.empty.find(row=>row.member.id==='short').count,0,'Future run cannot fulfil current goal');
const html=renderWeeklyOverview(rows,weeks,'2026-11',{today:'2026-11-04',memberPhoto:member=>member.id==='done'?'./photo.svg':''});
assert(!html.includes('<table'));assert(!html.includes('0/2'));
assert(html.includes('Splnen&#233;'));assert(html.includes('Ch&#253;ba 1 beh'));assert(html.includes('Ch&#253;baj&#250; 2 behy'));
assert(html.includes('1 beh pod limitom'));assert(html.includes('Short &lt;script&gt;'));assert(html.includes('src="./photo.svg"'));
const future=renderWeeklyOverview(rows,weeks,'2026-11',{today:'2026-11-04',selected:weeks[1].start});
assert(future.includes('week-not-started'));assert(!future.includes('class="week-member'));
const closed=renderWeeklyOverview(rows,weeks,'2026-11',{today:'2026-11-09',selected:weeks[0].start});
assert(closed.includes('Bez pokuty'));assert(closed.includes('2,50 &euro;'));assert(closed.includes('5,00 &euro;'));
const october=monthContributions([members[3]],[],'2026-10',new Date(2026,9,2));
const one=renderWeeklyOverview(october.rows,october.weeks,'2026-10',{today:'2026-10-02'});
assert.equal((one.match(/class="week-step /g)||[]).length,1);
assert(renderWeeklyOverview([],[],'2026-11').includes('muted'));
console.log('PASS: week selection, bonus Sunday, activity groups, 3km threshold, future runs, future/closed presentation, fines, single-run weeks, photos and escaping.');
