import assert from "node:assert/strict";
import { monthContributions, personalInsights } from "../insights.js";

const members = [{ id: "a" }, { id: "b" }];
const calculate = (day, runs = [], month = "2026-10") => monthContributions(members, runs, month, new Date(`${day}T12:00:00`));
assert.equal(calculate("2026-10-01").pool, 20);
assert.equal(calculate("2026-10-04").pool, 20, "Sunday is still open");
assert.equal(calculate("2026-10-05").pool, 25, "First completed week adds two missing runs");
assert.equal(calculate("2026-10-11").pool, 25);
assert.equal(calculate("2026-10-12").pool, 35);
assert.equal(calculate("2026-10-19").pool, 45);
assert.equal(calculate("2026-10-26").pool, 55);
assert.equal(calculate("2026-11-01").pool, 60, "All October weeks closed");
const recorded = [{ memberId: "a", date: "2026-10-02", distance: 5 }];
assert.equal(calculate("2026-10-05", recorded).pool, 22.5);
assert.equal(calculate("2026-10-05", recorded).rows[0].total, 10);
const current = calculate("2026-10-23", recorded);
assert.equal(current.rows.reduce((sum, row) => sum + row.total, 0), current.pool);
assert.equal(current.base + current.penalties, current.pool);
assert.equal(calculate("2026-09-01").pool, 20, "Future months have base only");
assert.equal(monthContributions([], [], "2026-10").pool, 0);
const novemberRuns = [{ memberId: "a", date: "2026-11-01", distance: 5 }, { memberId: "a", date: "2026-11-04", distance: 7 }];
assert.equal(calculate("2026-11-08", novemberRuns, "2026-11").pool, 20);
assert.equal(calculate("2026-11-09", novemberRuns, "2026-11").pool, 25);
const weekly = personalInsights(novemberRuns, "a", "2026-10", new Date(2026, 10, 4));
assert.equal(weekly.total, 0, "Monthly stats follow selected month");
assert.equal(weekly.weekly.total, 12, "Weekly stats follow current week, including bonus Sunday");
assert.equal(weekly.weekly.average, 6);
assert.equal(weekly.weekly.longest, 7);
console.log("PASS: base pool, Sunday/Monday boundaries, gradual weekly penalties, month-end, historical/future month, member totals, November exception and weekly statistics.");
